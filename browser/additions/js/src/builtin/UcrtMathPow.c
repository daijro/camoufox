/*
 * pow(x, y) as the Windows 11 Universal CRT computes it (ucrtbase.dll
 * 10.0.26100, x64, FMA3 code path), to the last bit.
 *
 * The algorithm is Szabolcs Nagy's pow from Arm's optimized-routines
 * (math/pow.c, Copyright (c) 2018-2020 Arm Limited, SPDX-License-Identifier:
 * MIT OR Apache-2.0 WITH LLVM-exception), restated here in the configuration
 * the CRT uses:
 *
 * - log(x) = k ln2 + log(c) + log1p(z/c - 1) with 128 subintervals
 *   (POW_LOG_TABLE_BITS 7) and a degree-8 polynomial; r = z/c - 1 is one fused
 *   multiply-add, and so is the error of A[0]*r*r;
 * - y log(x) as a head and an exact tail (one fma);
 * - exp(x) = 2^(k/N) exp(r) with N = 256 (EXP_TABLE_BITS 8), k from the
 *   "narrow" shift (EXP_USE_TOINT_NARROW) and the order-5 polynomial for
 *   |r| < ln2/256 (EXP_POLY_WIDE), with no fused operations;
 * - Arm's special cases, and its handling of results in the subnormal range
 *   (rounded once).
 *
 * glibc and musl ship the same pow with 128 exp entries, which is why their
 * results differ from Windows 11's in a few cases in ten thousand. Windows 10,
 * and Windows 11 before 24H2, ship a different pow (built on AMD LibM's); this
 * is the current Windows 11's.
 *
 * Each fma() below is one fused operation and every other operation rounds
 * once, so this must be built without FP contraction (the pragma below, and
 * -ffp-contract=off in moz.build). The tables come from their definitions,
 * generated by browser/scripts/gen-ucrt-math-tables.py; the polynomial
 * coefficients are Arm's minimax ones. NaN results have the bits x64 gives,
 * whatever the build machine's default NaN. The results are checked bit for
 * bit against ucrtbase.dll's, recorded on Windows 11
 * (browser/tests/ucrt-math/). errno and floating-point exception flags are not
 * reproduced.
 */
#include "builtin/UcrtMath.h"
#include "builtin/UcrtMathPowTables.h"

#include <math.h>
#include <stdint.h>
#include <string.h>

/* GCC ignores this pragma (and warns); -ffp-contract=off covers it there. */
#ifdef __clang__
#  pragma STDC FP_CONTRACT OFF
#endif

#if defined(__i386__) && !defined(__SSE2_MATH__)
#error "ucrt_pow needs SSE2 double arithmetic (no x87 excess precision)"
#endif

static inline double D(uint64_t b) {
  double x;
  memcpy(&x, &b, sizeof x);
  return x;
}

static inline uint64_t B(double x) {
  uint64_t b;
  memcpy(&b, &x, sizeof b);
  return b;
}

#define SIGN 0x8000000000000000ULL
#define QBIT 0x0008000000000000ULL
#define INF_BITS 0x7ff0000000000000ULL
#define ONE_BITS 0x3ff0000000000000ULL
/* x64's default NaN: what an invalid operation such as 0/0 returns. */
#define DEFAULT_NAN 0xfff8000000000000ULL

static inline uint32_t top12(double x) { return (uint32_t)(B(x) >> 52); }

static inline int is_nan(uint64_t b) { return (b & ~SIGN) > INF_BITS; }

/* x + y where one of them is NaN, as SSE2 computes it: the first NaN operand,
   quieted. */
static inline double nan_sum(double x, double y) {
  uint64_t bx = B(x), by = B(y);
  return D((is_nan(bx) ? bx : by) | QBIT);
}

static inline int is_signaling(double x) {
  uint64_t b = B(x);
  return is_nan(b) && !(b & QBIT);
}

/* Overflow and underflow, with the sign of a negative odd power. */
static inline double oflow(uint32_t sign) {
  return D(INF_BITS | (sign ? SIGN : 0));
}
static inline double uflow(uint32_t sign) { return D(sign ? SIGN : 0); }

/* Arm's log polynomial for log1p(r) - r - A[0] r^2 on |r| < 0x1.6bp-8,
   relative error 0x1.11922ap-70, scaled as it is evaluated. */
static const double A[7] = {
    -0x1p-1,
    0x1.555555555556p-2 * -2,
    -0x1.0000000000006p-2 * -2,
    0x1.999999959554ep-3 * 4,
    -0x1.555555529a47ap-3 * 4,
    0x1.2495b9b4845e9p-3 * -8,
    -0x1.0002b8b263fc3p-3 * -8,
};

/* Arm's exp polynomial for N == 256, EXP_POLY_ORDER 5, EXP_POLY_WIDE: abs
   error 1.5547*2^-66 if |r| < ln2/256. */
static const double C2 = 0x1.ffffffffffdbdp-2;
static const double C3 = 0x1.555555555543cp-3;
static const double C4 = 0x1.55555cf16e1edp-5;
static const double C5 = 0x1.1111167a4b553p-7;

/* 1.5 * 2^36 + 0.5: z + SHIFT holds round(z) from bit 16 up. */
static const double SHIFT = 0x1800000000.8p0;

#define POW_LOG_N (1 << POW_LOG_TABLE_BITS)
#define POW_LOG_OFF 0x3fe6955500000000ULL
#define EXP_N (1 << EXP_TABLE_BITS)
#define SIGN_BIAS (0x800 << EXP_TABLE_BITS)

/* hi + *tail = log(x), *tail about 15 bits beyond hi. ix is x's bits, a
   subnormal normalized with its exponent going negative. */
static inline double log_inline(uint64_t ix, double* tail) {
  uint64_t tmp = ix - POW_LOG_OFF;
  int i = (int)((tmp >> (52 - POW_LOG_TABLE_BITS)) % POW_LOG_N);
  int k = (int)((int64_t)tmp >> 52);
  uint64_t iz = ix - (tmp & 0xfffULL << 52);
  double z = D(iz);
  double kd = (double)k;

  double invc = D(POW_LOG_INVC[i]);
  double logc = D(POW_LOG_LOGC[i]);
  double logctail = D(POW_LOG_LOGCTAIL[i]);

  /* 1/c has few bits and |z/c - 1| < 1/N, so r is exact. */
  double r = fma(z, invc, -1.0);

  double t1 = kd * D(LN2HI) + logc;
  double t2 = t1 + r;
  double lo1 = kd * D(LN2LO) + logctail;
  double lo2 = t1 - t2 + r;

  double ar = A[0] * r;
  double ar2 = r * ar;
  double ar3 = r * ar2;
  double hi = t2 + ar2;
  double lo3 = fma(ar, r, -ar2);
  double lo4 = t2 - hi + ar2;
  double p =
      ar3 * (A[1] + r * A[2] + ar2 * (A[3] + r * A[4] + ar2 * (A[5] + r * A[6])));
  double lo = lo1 + lo2 + lo3 + lo4 + p;
  double y = hi + lo;
  *tail = hi - y + lo;
  return y;
}

/* scale * (1 + tmp) where that may overflow or land in the subnormal range.
   sbits is scale's bits with an exponent that may have wrapped; ki is the k
   of the reduction, negative on the underflow side. */
static inline double specialcase(double tmp, uint64_t sbits, uint64_t ki) {
  double scale, y;
  if ((ki & 0x80000000) == 0) {
    /* k > 0: scale's exponent may have overflowed by up to 460. */
    sbits -= 1009ULL << 52;
    scale = D(sbits);
    return 0x1p1009 * (scale + scale * tmp);
  }
  /* k < 0: round once into the subnormal range. */
  sbits += 1022ULL << 52;
  scale = D(sbits);
  y = scale + scale * tmp;
  if (fabs(y) < 1.0) {
    double hi, lo, one = 1.0;
    if (y < 0.0) {
      one = -1.0;
    }
    lo = scale - y + scale * tmp;
    hi = one + y;
    lo = one - hi + y + lo;
    y = (hi + lo) - one;
    /* The sign of zero. */
    if (y == 0.0) {
      y = D(sbits & SIGN);
    }
  }
  return 0x1p-1022 * y;
}

/* sign * exp(x + xtail), |xtail| < 2^-8/N; sign_bias is SIGN_BIAS or 0. */
static inline double exp_inline(double x, double xtail, uint32_t sign_bias) {
  uint32_t abstop = top12(x) & 0x7ff;
  if (abstop - top12(0x1p-54) >= top12(512.0) - top12(0x1p-54)) {
    if (abstop - top12(0x1p-54) >= 0x80000000) {
      /* Tiny x: 1 + x, rounded. */
      double one = 1.0 + x;
      return sign_bias ? -one : one;
    }
    if (abstop >= top12(1024.0)) {
      return (B(x) >> 63) ? uflow(sign_bias) : oflow(sign_bias);
    }
    /* Large x: special-cased below. */
    abstop = 0;
  }

  /* x = k ln2/N + r, r in [-ln2/2N, ln2/2N]. */
  double z = D(INVLN2N) * x;
  double kd = z + SHIFT;
  uint64_t ki = B(kd) >> 16;
  kd = (double)(int32_t)ki;
  double r = x + kd * D(NEGLN2HIN) + kd * D(NEGLN2LON);
  r += xtail;
  /* 2^(k/N) ~= scale * (1 + tail). */
  uint64_t idx = 2 * (ki % EXP_N);
  uint64_t top = (ki + sign_bias) << (52 - EXP_TABLE_BITS);
  double tail = D(EXP_TAB[idx]);
  uint64_t sbits = EXP_TAB[idx + 1] + top;
  double r2 = r * r;
  double tmp = tail + r + r2 * (C2 + r * C3) + r2 * r2 * (C4 + r * C5);
  if (abstop == 0) {
    return specialcase(tmp, sbits, ki);
  }
  double scale = D(sbits);
  return scale + scale * tmp;
}

/* 0: not an integer, 1: odd, 2: even. iy is a non-zero finite double's bits. */
static inline int checkint(uint64_t iy) {
  int e = (int)(iy >> 52 & 0x7ff);
  if (e < 0x3ff) {
    return 0;
  }
  if (e > 0x3ff + 52) {
    return 2;
  }
  if (iy & ((1ULL << (0x3ff + 52 - e)) - 1)) {
    return 0;
  }
  if (iy & (1ULL << (0x3ff + 52 - e))) {
    return 1;
  }
  return 2;
}

/* Whether i is the bits of 0, infinity or NaN. */
static inline int zeroinfnan(uint64_t i) {
  return 2 * i - 1 >= 2 * INF_BITS - 1;
}

double ucrt_pow(double x, double y) {
  uint32_t sign_bias = 0;
  uint64_t ix = B(x), iy = B(y);
  uint32_t topx = top12(x), topy = top12(y);

  if (topx - 0x001 >= 0x7ff - 0x001 ||
      (topy & 0x7ff) - 0x3be >= 0x43e - 0x3be) {
    /* x is subnormal, zero, infinite or NaN, or |y| < 2^-65, |y| >= 2^63
       or y is NaN. */
    if (zeroinfnan(iy)) {
      if (2 * iy == 0) {
        return is_signaling(x) ? nan_sum(x, y) : 1.0;
      }
      if (ix == ONE_BITS) {
        return is_signaling(y) ? nan_sum(x, y) : 1.0;
      }
      if (2 * ix > 2 * INF_BITS || 2 * iy > 2 * INF_BITS) {
        return nan_sum(x, y);
      }
      if (2 * ix == 2 * ONE_BITS) {
        return 1.0;
      }
      if ((2 * ix < 2 * ONE_BITS) == !(iy >> 63)) {
        return 0.0; /* |x| < 1 and y == inf, or |x| > 1 and y == -inf. */
      }
      return y * y;
    }
    if (zeroinfnan(ix)) {
      double x2 = x * x;
      if (ix >> 63 && checkint(iy) == 1) {
        x2 = -x2;
      }
      return iy >> 63 ? 1 / x2 : x2;
    }
    /* x and y are non-zero and finite. */
    if (ix >> 63) {
      int yint = checkint(iy);
      if (yint == 0) {
        return D(DEFAULT_NAN); /* (x - x) / (x - x) */
      }
      if (yint == 1) {
        sign_bias = SIGN_BIAS;
      }
      ix &= ~SIGN;
      topx &= 0x7ff;
    }
    if ((topy & 0x7ff) - 0x3be >= 0x43e - 0x3be) {
      /* y is not odd here, so sign_bias is 0. */
      if (ix == ONE_BITS) {
        return 1.0;
      }
      if ((topy & 0x7ff) < 0x3be) {
        /* |y| < 2^-65: x^y ~= 1 + y log(x). */
        return ix > ONE_BITS ? 1.0 + y : 1.0 - y;
      }
      return (ix > ONE_BITS) == (topy < 0x800) ? oflow(0) : uflow(0);
    }
    if (topx == 0) {
      /* Subnormal x: normalize, the exponent going negative. */
      ix = B(D(ix) * 0x1p52);
      ix &= ~SIGN;
      ix -= 52ULL << 52;
    }
  }

  double lo;
  double hi = log_inline(ix, &lo);
  double ehi = y * hi;
  double elo = y * lo + fma(y, hi, -ehi);
  return exp_inline(ehi, elo, sign_bias);
}
