/*
 * pow(x, y) as the Windows Universal CRT computes it on its FMA3 code path, to
 * the last bit: x^y = exp(y ln x), each half by P. T. P. Tang's table-driven
 * method.
 *
 * - ln x: "Table-driven implementation of the logarithm function in IEEE
 *   floating-point arithmetic", ACM TOMS 16(4), 1990. x = 2^e * Y with
 *   1/2 <= Y < 1, F is Y rounded to a multiple of 1/256 and r = (F - Y)/F, so
 *   ln x = e ln 2 + ln(2F) + ln(1 - r), the last by its Taylor series to r^7.
 * - exp(w): "Table-driven implementation of the exponential function in IEEE
 *   floating-point arithmetic", ACM TOMS 15(2), 1989. n = round(w * 64/ln 2) =
 *   64m + j and rr = w - n ln2/64, so exp(w) = 2^m * 2^(j/64) * exp(rr), the
 *   last by its Taylor series to rr^6.
 *
 * ln x is kept as a head and tail, and y ln x is formed exactly from 26-bit
 * halves (Dekker's product), as in AMD LibM's pow (aocl-libm-ose,
 * src/isa/avx/gas/pow.S, BSD-3-Clause), whose tables, constants, thresholds
 * and special-case flags these are. The CRT evaluates the polynomials by
 * Horner's rule with fused multiply-adds and, unlike that pow.S, has no
 * separate path for x near 1. Each fma() below is one fused operation and
 * every other operation rounds once, so this must be built without FP
 * contraction (the pragma below, and -ffp-contract=off in moz.build).
 *
 * The tables come from their definitions, generated by
 * browser/scripts/gen-ucrt-math-tables.py. The results are checked bit for bit
 * against ucrtbase.dll's, recorded on Windows (browser/tests/ucrt-math/).
 * errno and floating-point exception flags are not reproduced.
 */
#include "builtin/UcrtMath.h"
#include "builtin/UcrtMathPowTables.h"

#include <math.h>
#include <stdint.h>
#include <string.h>

/* GCC ignores this pragma (and warns); -ffp-contract=off covers it there. */
#ifdef __clang__
#  pragma STDC FP_CONTRACT OFF
#endif

#if defined(__i386__) && !defined(__SSE2_MATH__)
#error "ucrt_pow needs SSE2 double arithmetic (no x87 excess precision)"
#endif

#define SIGN 0x8000000000000000ULL
#define ABSM 0x7fffffffffffffffULL
#define EXPM 0x7ff0000000000000ULL
#define MANT 0x000fffffffffffffULL
#define QBIT 0x0008000000000000ULL
#define ONE 0x3ff0000000000000ULL
#define MONE 0xbff0000000000000ULL
#define INF 0x7ff0000000000000ULL
#define NINF 0xfff0000000000000ULL
#define QNAN_NEG 0xfff8000000000000ULL
#define HUGE_Y_EXP 0x43e0000000000000ULL /* 2^63 */
#define TINY_Y_EXP 0x3c00000000000000ULL /* 2^-63 */
#define YHI_MASK 0xfffffffff8000000ULL   /* keeps a double's top 26 bits */

/* AMD LibM's special-case flags (pow.S, .L__flag_*). */
enum {
  X_ONE_Y_SNAN = 1,
  X_ZERO_Z_INF = 2,
  X_NAN = 3,
  Y_NAN = 4,
  X_NAN_Y_NAN = 5,
  X_NEG_Y_NOTINT = 6,
  Z_ZERO = 7,
  Z_DENORMAL = 8,
  Z_INF = 9,
};

static inline double D(uint64_t b) {
  double x;
  memcpy(&x, &b, sizeof x);
  return x;
}

static inline uint64_t B(double x) {
  uint64_t b;
  memcpy(&b, &x, sizeof b);
  return b;
}

static inline int is_nan_bits(uint64_t u) {
  return (u & EXPM) == EXPM && (u & MANT) != 0;
}

/* A special case's result. AMD's pow passes it to an error handler with one of
   the flags above; Windows returns it, with the quiet bit set for the NaN
   flags (X_NAN to X_NAN_Y_NAN). */
static inline uint64_t special(int code, uint64_t z) {
  return (code >= X_NAN && code <= X_NAN_Y_NAN) ? (z | QBIT) : z;
}

/* x is a NaN. */
static uint64_t nan_x(uint64_t xb, uint64_t yb) {
  uint64_t qx = xb | QBIT;
  if (is_nan_bits(yb)) {
    /* Both are NaNs: which one Windows returns. */
    uint64_t qy = yb;
    if (qx == QNAN_NEG) {
      qx = qy;
    } else {
      if (qy == QNAN_NEG) {
        qy = qx;
      }
      if (qy & SIGN) {
        qy = qx;
      }
      if (qx & SIGN) {
        qx = qy;
      }
    }
    return special(X_NAN_Y_NAN, qx | QBIT);
  }
  return special(X_NAN, qx);
}

/* x is +-0. */
static uint64_t x_zero(uint64_t yb, uint64_t sign) {
  if ((yb & EXPM) == EXPM) {
    if (yb == NINF) {
      return INF;
    }
    if (yb == INF) {
      return 0;
    }
    return special(Y_NAN, yb | QBIT);
  }
  if (yb & SIGN) {
    return special(X_ZERO_Z_INF, INF | sign);
  }
  return sign;
}

/* x is +-inf or NaN. */
static uint64_t x_infnan(uint64_t xb, uint64_t yb, uint64_t sign) {
  uint64_t r = (yb & SIGN) ? 0 : INF;
  if (xb & MANT) {
    return nan_x(xb, yb);
  }
  if (is_nan_bits(yb)) {
    return special(Y_NAN, yb | QBIT);
  }
  return r | sign;
}

/* x is -1. */
static uint64_t x_minus_one(uint64_t yb, uint64_t sign) {
  if (is_nan_bits(yb)) {
    return special(Y_NAN, yb | QBIT);
  }
  return ONE | sign;
}

/* |y| >= 2^63, inf or NaN. */
static uint64_t y_huge(uint64_t xb, uint64_t yb) {
  uint64_t r;
  if ((xb & EXPM) == EXPM) {
    return x_infnan(xb, yb, 0);
  }
  if ((xb & ABSM) == 0) {
    return x_zero(yb, 0);
  }
  if (xb == MONE) {
    return x_minus_one(yb, 0);
  }
  if ((int64_t)(xb & ABSM) < (int64_t)ONE) {
    r = (yb & SIGN) ? INF : 0;
  } else {
    r = (yb & SIGN) ? 0 : INF;
  }
  if (is_nan_bits(yb)) {
    return special(Y_NAN, yb | QBIT);
  }
  if ((yb & EXPM) == EXPM) {
    return r;
  }
  return special((r & ABSM) ? Z_INF : Z_ZERO, r);
}

/* x positive, finite, nonzero, != 1; y finite and not tiny. */
static uint64_t core(uint64_t xb, uint64_t yb, uint64_t sign) {
  int64_t xexp = (int64_t)(xb >> 52) - 0x3ff;
  uint64_t m = xb & MANT;
  uint64_t ib = xb;

  if (xexp == -1023) {
    /* Subnormal x. */
    uint64_t tb = B(D(m | ONE) - 1.0);
    m = tb & MANT;
    ib = m;
    xexp = (int64_t)(int32_t)(uint32_t)((tb >> 52) - 0x7fd);
  }
  double e = (double)(int32_t)xexp;

  /* F: Y rounded to the nearest 1/256, and its table index. */
  uint64_t idx_bits = (ib & 0x000ff00000000000ULL) + ((ib & 0x0000080000000000ULL) << 1);
  double F = D(idx_bits | 0x3fe0000000000000ULL);
  double f = D(m | 0x3fe0000000000000ULL);
  unsigned idx = (unsigned)(idx_bits >> 44);

  double u = F - f;
  double u1 = u * D(INV_HEAD[idx]);
  double u2 = u * D(INV_TAIL[idx]);
  double r = u1 + u2;
  double r2 = r * r;
  double corr = (u1 - r) + u2;
  double p = D(LOG_C[5]);
  p = fma(p, r, D(LOG_C[4]));
  p = fma(p, r, D(LOG_C[3]));
  p = fma(p, r, D(LOG_C[2]));
  p = fma(p, r, D(LOG_C[1]));
  p = fma(p, r, D(LOG_C[0]));
  p = fma(p, r2, corr);
  double t3 = fma(e, D(LN2_TAIL), -p) + D(LOG_TAIL[idx]);
  double t1 = t3;
  t3 = t3 - r;
  double h = fma(e, D(LN2_HEAD), D(LOG_HEAD[idx]));
  double s = h + t3;
  double lhi = D(B(s) & YHI_MASK);
  double y = D(yb);
  double yhi = D(yb & YHI_MASK);
  double r2b = r + t3;
  double h7 = h - s;
  t1 = t1 - r2b;
  h7 = h7 + t3;
  double s5 = s - lhi;
  h7 = h7 + t1;
  double llo = h7 + s5;
  double ylo = y - yhi;

  double a3 = ylo * llo;
  double a4 = ylo * lhi;
  double a5 = llo * yhi;
  double a6 = lhi * yhi;
  a3 = a3 + a4;
  a3 = a3 + a5;
  double w = a6 + a3;
  double wt = (a6 - w) + a3;

  /* exp(w + wt). */
  uint64_t wb = B(w);
  double v = w * D(SIXTY4_BY_LN2);
  if (v > 65536.0) {
    return special(Z_INF, INF | sign);
  }
  if (!(v >= -68800.0)) {
    return special(Z_ZERO, sign);
  }
  int32_t n = (int32_t)lrint(v); /* in the current rounding mode, as pow.S */
  double nf = (double)n;
  double w0 = fma(-nf, D(LN2_BY_64_HEAD), w);
  int32_t j = n & 0x3f;
  int32_t mexp = (n - j) >> 6;
  double rr = (w0 + nf * D(LN2_BY_64_TAIL)) + wt;
  double q = D(EXP_C[0]);
  q = fma(q, rr, D(EXP_C[1]));
  q = fma(q, rr, D(EXP_C[2]));
  q = fma(q, rr, D(EXP_C[3]));
  q = fma(q, rr, D(EXP_C[4]));
  q = fma(q, rr, D(EXP_C[5]));
  q = q * rr;
  int32_t sub_m = mexp <= -1022 ? mexp : 0;
  uint64_t scale = (((uint64_t)(uint32_t)mexp + 0x3ff) << 52);
  double z5 = q * D(EXP_TAIL[j]) + D(EXP_TAIL[j]);
  double z = (q * D(EXP_HEAD[j]) + z5) + D(EXP_HEAD[j]);

  if (scale == INF) {
    /* m == 1024. */
    if (z >= 1.0) {
      return special(Z_INF, INF | sign);
    }
    return B(z) | 0x7fe0000000000000ULL | sign;
  }
  if (sub_m == 0) {
    return B(z * D(scale)) | sign;
  }
  if ((z >= 1.0 ? sub_m : 0) == -1022) {
    return B(z * D(scale)) | sign;
  }
  /* Subnormal result. */
  if ((int64_t)wb > (int64_t)DENORM_W_LIM) {
    return special(Z_DENORMAL, 1 | sign);
  }
  int32_t c = sub_m + 0x432;
  if (c < 0) {
    c = 0;
  }
  return special(Z_DENORMAL, B(z * D(1ULL << (c & 63))) | sign);
}

static uint64_t ucrt_pow_bits(uint64_t xb, uint64_t yb) {
  uint64_t sign = 0;

  if ((yb & ABSM) == 0) {
    /* y == +-0. */
    if (is_nan_bits(xb) && !(xb & QBIT)) {
      return nan_x(xb, yb);
    }
    return ONE;
  }
  if (yb == ONE) {
    return is_nan_bits(xb) ? nan_x(xb, yb) : xb;
  }
  if (xb & SIGN) {
    /* Negative x: the result is negated for an odd integer y. */
    if ((int64_t)(yb & EXPM) > (int64_t)HUGE_Y_EXP) {
      return y_huge(xb, yb);
    }
    uint64_t ay = yb & ABSM;
    int64_t ye = (int64_t)(ay >> 52) - 0x3ff;
    int nonint = 0;
    if (ye < 0) {
      nonint = 1;
    } else if (ye <= 0x35) {
      if ((MANT >> ye) & ay) {
        nonint = 1;
      } else if ((0x0010000000000000ULL >> ye) & ay) {
        sign = SIGN;
      }
    }
    if (nonint) {
      if ((xb & EXPM) == EXPM) {
        return x_infnan(xb, yb, sign);
      }
      if (xb == SIGN) {
        return x_zero(yb, sign);
      }
      return special(X_NEG_Y_NOTINT, QNAN_NEG);
    }
    if (xb == SIGN) {
      return x_zero(yb, sign);
    }
    if (xb == MONE) {
      return x_minus_one(yb, sign);
    }
    if ((xb & EXPM) == EXPM) {
      return x_infnan(xb, yb, sign);
    }
    return core(xb & ABSM, yb, sign);
  }
  if (xb == ONE) {
    if (is_nan_bits(yb) && !(yb & QBIT)) {
      return special(Y_NAN, yb | QBIT);
    }
    return ONE;
  }
  if (xb == 0) {
    return x_zero(yb, sign);
  }
  if ((xb & EXPM) == EXPM) {
    return x_infnan(xb, yb, sign);
  }
  if ((int64_t)(yb & EXPM) > (int64_t)HUGE_Y_EXP) {
    return y_huge(xb, yb);
  }
  if ((int64_t)(yb & EXPM) < (int64_t)TINY_Y_EXP) {
    /* |y| < 2^-63: x^y rounds to 1 + y. */
    return B(D(yb) + 1.0);
  }
  return core(xb, yb, sign);
}

double ucrt_pow(double x, double y) {
  return D(ucrt_pow_bits(B(x), B(y)));
}
