/*
 * sin, cos and tan as the Windows Universal CRT computes them on its FMA3 code
 * path, to the last bit.
 *
 * Above pi/4, x = n pi/2 + r, with r carried as a head and tail (r, rr) and n
 * mod 4 choosing the kernel and sign:
 * - |x| < 2e7: Cody and Waite's reduction (W. J. Cody and W. Waite, Software
 *   Manual for the Elementary Functions, 1980), pi/2 in three parts with
 *   fused multiply-adds for the products. This split and the 2e7 limit are
 *   the CRT's own: AMD LibM splits pi/2 differently and switches to
 *   Payne-Hanek at 5e5.
 * - Larger |x|: Payne and Hanek's reduction (M. H. Payne and R. N. Hanek,
 *   "Radian reduction for trigonometric functions", ACM SIGNUM Newsletter
 *   18(1), 1983), as AMD LibM's __amd_remainder_piby2 does it
 *   (aocl-libm-ose, src/isa/avx/gas/remainder_piby2_new.S, BSD-3-Clause):
 *   three 64x64->128-bit products of the significand with 2/pi's bits.
 *   reduce_large follows that routine step by step, with fused multiply-adds
 *   in the final product by pi/2, and names its variables after the
 *   routine's registers so the two can be read side by side.
 * - Kernels on [-pi/4, pi/4]: AMD LibM's minimax polynomials for sin (degree
 *   13) and cos (degree 14), with its correction for rr (src/isa/avx/gas/sin.S
 *   and cos.S), and its rational approximation for tan, with tan(pi/4 - x)
 *   above 0.68 (src/isa/avx2/include/trig_func.h, tan_piby4_s_fma3).
 *
 * Each fma() is one fused operation and every other operation rounds once, so
 * this must not be built with FP contraction (pragma below, and
 * -ffp-contract=off in moz.build). The constants that follow from pi are
 * generated by browser/scripts/gen-ucrt-math-tables.py. The results are
 * checked bit for bit against ucrtbase.dll's, recorded on Windows
 * (browser/tests/ucrt-math/). Floating-point exception and errno side effects
 * are not reproduced. A NaN argument comes back quieted, and an infinite one
 * gives x64's default NaN (sign bit set), as the CRT returns them: Math.sin
 * and friends hand the bits to the page unchanged.
 */
#include "builtin/UcrtMath.h"
#include "builtin/UcrtMathTrigTables.h"

#include <math.h>
#include <stdint.h>
#include <string.h>

/* GCC ignores this pragma (and warns); -ffp-contract=off covers it there. */
#ifdef __clang__
#  pragma STDC FP_CONTRACT OFF
#endif

#if defined(__i386__) && !defined(__SSE2_MATH__)
#  error "ucrt_trig needs SSE2 double arithmetic (no x87 excess precision)"
#endif

#define SIGN 0x8000000000000000ULL
#define MANT 0x000fffffffffffffULL

static inline uint64_t bits(double x) {
  uint64_t b;
  memcpy(&b, &x, sizeof x);
  return b;
}

static inline double dbl(uint64_t b) {
  double x;
  memcpy(&x, &b, sizeof x);
  return x;
}

#define K_ONE 0x3ff0000000000000ULL
#define K_TWO 0x4000000000000000ULL
#define K_MONE 0xbff0000000000000ULL      /* -1 */
#define K_HALF 0x3fe0000000000000ULL
#define K_TINY 0x3e40000000000000ULL      /* 2^-27 */
#define K_SMALL 0x3f20000000000000ULL     /* 2^-13 */
#define K_LARGE 0x417312d000000000ULL     /* 2e7: Payne-Hanek from here */
#define K_INF 0x7ff0000000000000ULL
#define K_SHIFT 0x4338000000000000ULL     /* 1.5 * 2^52: rounds to an integer */
#define K_HI_MASK 0xfffffffff8000000ULL   /* keeps a double's top 26 bits */
#define K_TAN_MASK 0xffffffff00000000ULL  /* keeps a double's top 21 bits */
#define K_NPOINT68 (K_POINT68 | SIGN)

/* cos(r) = 1 - r^2/2 + r^4 (C0 + C1 r^2 + ... + C5 r^10), sin(r) = r +
   r^3 (S0 + S1 r^2 + ... + S5 r^10): C0 = 1/24 and S0 = -1/6, rounded to
   nearest; the rest are AMD LibM's minimax coefficients. */
static const uint64_t COS_C[6] = {
    0x3fa5555555555555ULL, 0xbf56c16c16c16967ULL, 0x3efa01a019f4ec91ULL,
    0xbe927e4fa17f667bULL, 0x3e21eeb690382eecULL, 0xbda907db47258aa7ULL,
};
static const uint64_t SIN_C[6] = {
    0xbfc5555555555555ULL, 0x3f81111111110bb3ULL, 0xbf2a01a019e83e5cULL,
    0x3ec71de3796cde01ULL, 0xbe5ae600b42fdfa7ULL, 0x3de5e0b2f9a43bb8ULL,
};
/* tan(x) = x + x^3 P(x^2) / Q(x^2): AMD LibM's tan_c1 ... tan_c7, with c7
   negated (AMD applies it with a negated multiply-add). */
static const uint64_t TAN_P[3] = {
    0x3fd7d50f6638564aULL, 0xbf977c24c7569abbULL, 0x3f2d5daf289c385aULL,
};
static const uint64_t TAN_Q[4] = {
    0x3ff1dfcb8caa40b8ULL, 0xbfe08046499eb90fULL, 0x3f9ab0f4f80a0acfULL,
    0xbf2e7517ef6d98f8ULL,
};

static inline uint64_t load64(int off) {
  uint64_t v = 0;
  for (int i = 7; i >= 0; i--) {
    v = (v << 8) | TWOBYPI[off + i];
  }
  return v;
}

/* bsr leaves the destination unchanged when the source is zero (AMD and Intel). */
static inline uint64_t bsr(uint64_t v, uint64_t dest) {
  return v ? (uint64_t)(63 - __builtin_clzll(v)) : dest;
}

/* |x| < 2e7. */
static double reduce_medium(double x, double* rr, int* region) {
  double shift = dbl(K_SHIFT);
  double npi2 = fma(x, dbl(K_TWOBYPI), shift) - shift;
  *region = (int)npi2 & 3;
  double piby2_2 = dbl(K_PIBY2_2);
  double rhead = fma(-npi2, dbl(K_PIBY2_1), x);
  double rtail = npi2 * piby2_2;
  double err = fma(piby2_2, npi2, -rtail);
  double r5 = rhead - rtail;
  double t4 = (rhead - r5) - rtail;
  double rhead2 = fma(-npi2, piby2_2, rhead);
  r5 = ((r5 - rhead2) + t4) - err;
  *rr = fma(-npi2, dbl(K_PIBY2_3), r5);
  return rhead2;
}

/* |x| >= 2e7: __amd_remainder_piby2. TWOBYPI is read from byte 7 (the
   largest exponent) to byte 154 (2e7). */
static double reduce_large(double x, double* rr, int* region) {
  uint64_t xb = bits(x);
  uint64_t e = (xb >> 52) - 0x3FF;
  int off = 0x86 - (int)(e >> 3);
  uint64_t m = (xb & MANT) | (1ULL << 52);

  unsigned __int128 p0 = (unsigned __int128)load64(off) * m;
  uint64_t r8 = (uint64_t)p0, r10 = (uint64_t)(p0 >> 64);
  unsigned __int128 p1 = (unsigned __int128)load64(off + 8) * m;
  unsigned __int128 s = (unsigned __int128)(uint64_t)p1 + r10;
  uint64_t r9 = (uint64_t)s;
  r10 = (uint64_t)(p1 >> 64) + (uint64_t)(s >> 64);
  r10 += load64(off + 16) * m;

  uint64_t r11 = e & 7;
  unsigned cl = (unsigned)((0x36 - r11) & 63);
  uint64_t rax = r10 >> cl;
  uint64_t cf = cl ? (r10 >> (cl - 1)) & 1 : 0;
  uint64_t rdx = 0;
  if (cf) {
    r10 = ~r10;
    r9 = ~r9;
    r8 = ~r8;
    rdx = SIGN;
  }
  *region = (int)((rax + cf) & 3);

  cl = (unsigned)((r11 + 10) & 63);
  r10 = (r10 << cl) >> cl;
  uint64_t rcx = bsr(r10, r11 + 10);
  r11 = r11 + 10 - 0x40;
  if (r10 == 0) {
    r10 = r9;
    r9 = r8;
    r8 = 0;
    rcx = bsr(r10, rcx);
    r11 -= 0x40;
  }
  r11 += rcx;
  rcx -= 0x34;
  if ((int64_t)rcx > 0) {
    unsigned c = (unsigned)(rcx & 63);
    uint64_t top = r10;
    r10 >>= c;
    r9 >>= c;
    r9 |= top << ((0x40 - rcx) & 63);
  } else if ((int64_t)rcx < 0) {
    uint64_t n = -rcx;
    unsigned c = (unsigned)(n & 63);
    unsigned c2 = (unsigned)((0x40 - n) & 63);
    uint64_t low = r9;
    r10 <<= c;
    r9 <<= c;
    r10 |= low >> c2;
    r8 >>= c2;
    r9 |= r8;
  }
  r11 += 0x3FF;
  r10 &= ~(1ULL << 52);
  r10 |= rdx;
  rcx = r11 << 52;
  r10 |= rcx;
  double hi = dbl(r10);

  rcx = bsr(r9, rcx);
  rcx = 0x40 - rcx;
  r9 = (r9 << (rcx & 63)) >> 12;
  rcx += 0x34;
  r11 -= rcx;
  r9 |= rdx | (r11 << 52);
  double lo = dbl(r9);

  double piby2 = dbl(K_PIBY2_1), p1h = dbl(K_PIBY2_H), p2 = dbl(K_PIBY2_M);
  double hi_top = dbl(bits(hi) & K_HI_MASK);
  double hi_bot = hi - hi_top;
  double r5 = hi * piby2;
  double t = hi_top * p1h - r5;
  t = fma(hi_bot, p1h, t);
  t = fma(hi_top, p2, t);
  t = fma(hi_bot, p2, t);
  double u = fma(hi, dbl(K_PIBY2_L), lo * piby2);
  t = t + u;
  double r = r5 + t;
  *rr = (r5 - r) + t;
  return r;
}

static double reduce(double ax, double* rr, int* region) {
  if (bits(ax) >= K_LARGE) {
    return reduce_large(ax, rr, region);
  }
  return reduce_medium(ax, rr, region);
}

static double cos_kernel(double r, double rr, double x2) {
  double one = dbl(K_ONE);
  double h = x2 * dbl(K_HALF);
  double t = one - h;
  double tail = fma(-r, rr, (one - t) - h);
  double p = fma(x2, dbl(COS_C[5]), dbl(COS_C[4]));
  for (int k = 3; k >= 0; k--) {
    p = fma(p, x2, dbl(COS_C[k]));
  }
  return fma(p, x2 * x2, tail) + t;
}

static double sin_kernel(double r, double rr, double x2) {
  double p = fma(x2, dbl(SIN_C[5]), dbl(SIN_C[4]));
  for (int k = 3; k >= 1; k--) {
    p = fma(p, x2, dbl(SIN_C[k]));
  }
  double x3 = r * x2;
  double t = (rr * dbl(K_HALF)) - x3 * p;
  t = x2 * t - rr;
  t = fma(-x3, dbl(SIN_C[0]), t);
  return r - t;
}

/* sin, cos or tan of an infinity or NaN: the NaN quieted, or for an infinity
   the default NaN x64 produces for an invalid operation. */
static inline double not_finite(uint64_t xb) {
  return dbl((xb & ~SIGN) > K_INF ? xb | 0x0008000000000000ULL
                                  : 0xfff8000000000000ULL);
}

double ucrt_sin(double x) {
  uint64_t xb = bits(x);
  uint64_t a = xb & ~SIGN;
  if (a >= K_PIBY4) {
    if (a >= K_INF) {
      return not_finite(xb);
    }
    double rr;
    int region;
    double r = reduce(dbl(a), &rr, &region);
    double x2 = r * r;
    double res = (region & 1) ? cos_kernel(r, rr, x2) : sin_kernel(r, rr, x2);
    uint64_t flip = ((region & 2) ? SIGN : 0) ^ (xb & SIGN);
    return dbl(bits(res) ^ flip);
  }
  if (a >= K_SMALL) {
    double x2 = x * x;
    double p = fma(x2, dbl(SIN_C[5]), dbl(SIN_C[4]));
    for (int k = 3; k >= 0; k--) {
      p = fma(p, x2, dbl(SIN_C[k]));
    }
    return fma(x * x2, p, x);
  }
  if (a >= K_TINY) {
    return fma(-((x * x) * x), dbl(K_SIXTH), x);
  }
  return x;
}

double ucrt_cos(double x) {
  uint64_t xb = bits(x);
  uint64_t a = xb & ~SIGN;
  double one = dbl(K_ONE);
  if (a > K_PIBY4) {
    if ((xb & K_INF) == K_INF) {
      return not_finite(xb);
    }
    double rr;
    int region;
    double r = reduce(dbl(a), &rr, &region);
    double x2 = r * r;
    double res = (region & 1) ? sin_kernel(r, rr, x2) : cos_kernel(r, rr, x2);
    uint64_t flip = ((region + 1) & 2) ? SIGN : 0;
    return dbl(bits(res) ^ flip);
  }
  if (a >= K_SMALL) {
    double x2 = x * x;
    double p = fma(dbl(COS_C[5]), x2, dbl(COS_C[4]));
    for (int k = 3; k >= 0; k--) {
      p = fma(p, x2, dbl(COS_C[k]));
    }
    p = fma(x2, p, -dbl(K_HALF));
    return fma(x2, p, one);
  }
  if (a >= K_TINY) {
    return fma(-(x * dbl(K_HALF)), x, one);
  }
  return one;
}

static double tan_poly(double x2, double* q_out) {
  double q = fma(dbl(TAN_Q[3]), x2, dbl(TAN_Q[2]));
  double p = fma(dbl(TAN_P[2]), x2, dbl(TAN_P[1]));
  q = fma(q, x2, dbl(TAN_Q[1]));
  p = fma(p, x2, dbl(TAN_P[0]));
  q = fma(q, x2, dbl(TAN_Q[0]));
  *q_out = q;
  return p;
}

double ucrt_tan(double x) {
  uint64_t xb = bits(x);
  uint64_t a = xb & ~SIGN;
  double piby4 = dbl(K_PIBY4), piby4_lo = dbl(K_PIBY4_LO);
  double one = dbl(K_ONE), two = dbl(K_TWO);

  if (a < K_PIBY4) {
    double w = 0.0;
    if (a > K_POINT68) {
      if (x < 0.0) {
        w = dbl(K_MONE);
        x = (piby4 + x) + piby4_lo;
      } else {
        w = one;
        x = (piby4 - x) + piby4_lo;
      }
    } else if (a < K_TINY) {
      return x;
    }
    double x2 = x * x;
    double q;
    double p = tan_poly(x2, &q);
    x = fma(x, (p / q) * x2, x);
    if (w == 0.0) {
      return x;
    }
    return fma(-(x / (x + one)), two, one) * w;
  }

  if (a >= K_INF) {
    return not_finite(xb);
  }
  double rr;
  int region;
  double r = reduce(dbl(a), &rr, &region);
  double w = 0.0;
  if (r > dbl(K_POINT68)) {
    w = one;
    r = (piby4 - r) + (piby4_lo - rr);
    rr = 0.0;
  } else if (!(r >= dbl(K_NPOINT68))) {
    w = dbl(K_MONE);
    r = (piby4 + r) + (piby4_lo + rr);
    rr = 0.0;
  }
  double r2 = fma(rr * r, two, r * r);
  double p = fma(dbl(TAN_P[2]), r2, dbl(TAN_P[1]));
  p = fma(p, r2, dbl(TAN_P[0]));
  double q = fma(dbl(TAN_Q[3]), r2, dbl(TAN_Q[2]));
  q = fma(q, r2, dbl(TAN_Q[1]));
  q = fma(q, r2, dbl(TAN_Q[0]));
  double tail = fma(r, (p / q) * r2, rr);
  double t = r + tail;
  double res;
  if (w != 0.0) {
    if (region & 1) {
      res = fma(t / (t - one), two, -one) * w;
    } else {
      res = fma(-(t / (t + one)), two, one) * w;
    }
  } else if (region & 1) {
    double t_hi = dbl(bits(t) & K_TAN_MASK);
    double tail2 = tail - (t_hi - r);
    double z = dbl(K_MONE) / t;
    double z_hi = dbl(bits(z) & K_TAN_MASK);
    double u = fma(z_hi, t_hi, one);
    u = fma(tail2, z_hi, u);
    res = fma(z, u, z_hi);
  } else {
    res = t;
  }
  return dbl(bits(res) ^ (xb & SIGN));
}
