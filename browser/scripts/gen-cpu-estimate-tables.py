#!/usr/bin/env python3
"""
Generate SkCpuEstimateTables.h from the recorded RCPPS/RSQRTPS tables.

    python3 scripts/gen-cpu-estimate-tables.py           # write the header
    python3 scripts/gen-cpu-estimate-tables.py --check   # fail if it is stale

The tables are what Intel's and AMD's instructions return, recorded on each
vendor's CPU by tests/cpu-estimates/record.py; neither vendor publishes them.
SkCpuEstimates.h explains the layout and the functions that read them.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECORDED = ROOT / "tests" / "cpu-estimates" / "recorded"
PROVENANCE = ROOT / "tests" / "cpu-estimates" / "provenance.json"
OUT = ROOT / "additions" / "gfx" / "skia" / "skia" / "src" / "opts" / "SkCpuEstimateTables.h"
VENDORS = ("intel", "amd")  # index = SK_CPU_VENDOR_* - 1
ENTRIES = 3 * 4096


def render():
    prov = json.loads(PROVENANCE.read_text())
    out = [
        "/* This Source Code Form is subject to the terms of the Mozilla Public",
        " * License, v. 2.0. If a copy of the MPL was not distributed with this",
        " * file, You can obtain one at http://mozilla.org/MPL/2.0/. */",
        "",
        "/* Generated by browser/scripts/gen-cpu-estimate-tables.py from",
        " * browser/tests/cpu-estimates/recorded; do not edit. RCPPS/RSQRTPS outputs",
        " * recorded on:",
    ]
    for vendor in VENDORS:
        for cpu in prov[vendor]["cpus"]:
            out.append(f" *   {vendor}: {cpu['cpu']}")
    out += [" * Layout and use: SkCpuEstimates.h. */", "",
            "#ifndef SkCpuEstimateTables_DEFINED", "#define SkCpuEstimateTables_DEFINED", "",
            '#include "SkCpuEstimates.h"', "",
            "static const uint32_t kSkCpuEstimateTables[2][SK_CPU_ESTIMATE_TABLE_SIZE] = {"]
    for vendor in VENDORS:
        words = (RECORDED / f"{vendor}.txt").read_text().split()
        if len(words) != ENTRIES:
            sys.exit(f"{vendor}.txt has {len(words)} entries, not {ENTRIES}")
        out.append(f"  {{ /* {vendor} */")
        for i in range(0, ENTRIES, 8):
            out.append("    " + ", ".join(f"0x{w}u" for w in words[i:i + 8]) + ",")
        out.append("  },")
    out += ["};", "", "#endif", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the header is stale")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run scripts/gen-cpu-estimate-tables.py")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
