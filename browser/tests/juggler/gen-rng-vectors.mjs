// Writes browser/tests/humanize/rng-vectors.json from the browser's own HumanizeRng.js.
// The launchers' client-side streams (custom() engines) are tested against
// this file, and rng.test.mjs checks the browser still produces it.
//
//   node browser/tests/juggler/gen-rng-vectors.mjs
import * as fs from 'node:fs';
import * as path from 'node:path';
import {fileURLToPath} from 'node:url';
import {load} from './gecko.mjs';

const {channelStream, splitmix64} = await load('input/HumanizeRng.js');

export const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../humanize/rng-vectors.json');
export const SEEDS = ['0', '1', '1234', '1235', '4294967295', '4294967296', '9223372036854775808',
  '18446744073709551615', '12345678901234567890', '6148914691236517205'];
export const DRAWS = 64;

export function vectors() {
  return {
    comment: 'Generated by browser/tests/juggler/gen-rng-vectors.mjs from browser/additions/juggler/input/HumanizeRng.js. ' +
      'Each draw is round(x * 2**32), an exact integer.',
    splitmix64: SEEDS.map(s => [s, splitmix64(BigInt(s)).toString()]),
    streams: SEEDS.map(seed => ({
      seed,
      ...Object.fromEntries(['mouse', 'keyboard', 'scroll'].map(channel => {
        const stream = channelStream(BigInt(seed), channel);
        return [channel, Array.from({length: DRAWS}, () => Math.round(stream() * 2 ** 32))];
      })),
    })),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  fs.writeFileSync(OUT, JSON.stringify(vectors(), null, 1)
      // one line per list of numbers
      .replace(/\[\n\s*([-\d",\s]+?)\n\s*\]/g, (_, inner) => `[${inner.split(/,\s*/).join(', ')}]`) + '\n');
